import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

const rebuttal = process.env.REBUTTAL_URL ?? 'http://127.0.0.1:3000';
const paper = process.env.PAPER_URL ?? 'http://127.0.0.1:8767';
const browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
const context = await browser.newContext({viewport:{width:1440,height:1024},deviceScaleFactor:1});
const page = await context.newPage();
const errors=[];
page.on('pageerror', error=>errors.push(error.message));
await mkdir('docs',{recursive:true});
try {
  await page.goto(rebuttal);
  await page.getByText('已载入保存版本',{exact:true}).waitFor();
  await page.screenshot({path:'docs/rebuttal.png',fullPage:true});
  const original=(await (await context.request.get(rebuttal+'/api/drafts')).json()).documents[0];
  await page.locator('.document.en').getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'编辑英文回复',exact:true}).fill(original.en+'\n\nBrowser smoke test.');
  await page.getByRole('button',{name:'保存版本',exact:true}).click();
  await page.getByText('已保存到工作台 · v'+(original.revision+1),{exact:true}).waitFor();
  await page.reload();
  await page.getByText('Browser smoke test.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'版本记录',exact:true}).click();
  await page.locator('.history-layout nav button').filter({hasText:original.revision===0?'初始稿':'v'+original.revision}).last().click();
  await page.getByRole('button',{name:'恢复此版本',exact:true}).click();
  await page.getByText('已保存到工作台 · v'+(original.revision+2),{exact:true}).waitFor();
  await page.getByRole('tab',{name:'原始审稿',exact:true}).click();
  await page.getByRole('button',{name:'中英对照',exact:true}).click();
  assert.equal(await page.locator('.original-review').count(),1);
  await page.getByRole('tab',{name:/逐点核对/}).click();
  assert.equal(await page.locator('.review-check-card').count(),2);
  await page.goto(paper);
  await page.locator('#right #motivation').waitFor();
  await page.waitForFunction(()=>window.MathJax?.startup?.document?.math);
  await page.screenshot({path:'docs/paper-compare.png',fullPage:true});
  await page.locator('#right #motivation .pair').click();
  assert.equal(await page.locator('#ref-intro.selected').count(),1);
  await page.locator('#right #motivation .annotation-trigger').click();
  await page.locator('#annotation-body').fill('Browser test: clarify the problem statement.');
  await page.locator('#annotation-save').click();
  await page.getByText('Browser test: clarify the problem statement.',{exact:true}).waitFor();
  await page.reload();
  await page.getByText('Browser test: clarify the problem statement.',{exact:true}).waitFor();
  const card=page.locator('.annotation-card').filter({hasText:'Browser test: clarify the problem statement.'});
  await card.getByRole('button',{name:'标为已处理',exact:true}).click();
  await page.locator('[data-note-filter="resolved"]').click();
  await card.getByRole('button',{name:'恢复待修改',exact:true}).waitFor();
  await card.getByRole('button',{name:'删除',exact:true}).click();
  await page.locator('#annotation-toast').getByRole('button',{name:'撤销',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: bilingual edit/save/reload/restore, reviews, alignment, annotation persistence/resolve/delete.');
} finally {await browser.close();}
